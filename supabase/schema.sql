-- clubs of the signed-in parent's children
create or replace function public.my_children_clubs()
returns setof text language sql stable security definer set search_path = public as $$
  select distinct p.club from public.parent_links l join public.profiles p on p.id = l.student_id
   where l.parent_id = auth.uid() and p.club is not null;
$$;

create or replace function public.new_link_code()
returns text language plpgsql volatile set search_path = public as $$
declare v text;
begin
  loop
    -- no 0/O/1/I so it is easy to read out over the phone
    v := (select string_agg(substr('ABCDEFGHJKLMNPQRSTUVWXYZ23456789', 1 + floor(random() * 32)::int, 1), '')
            from generate_series(1, 6));
    exit when not exists (select 1 from public.profiles where link_code = v);
  end loop;
  return v;
end $$;

create or replace function public.profiles_before_write()
returns trigger language plpgsql set search_path = public as $$
begin
  if new.role = 'student' and new.link_code is null then new.link_code := public.new_link_code(); end if;
  return new;
end $$;
drop trigger if exists profiles_before_write on public.profiles;
create trigger profiles_before_write before insert or update on public.profiles
  for each row execute function public.profiles_before_write();
update public.profiles set link_code = public.new_link_code() where role = 'student' and link_code is null;

-- Create the profile row automatically on sign-up (works even when
-- "Confirm email" is on and the browser has no session yet).
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, full_name, role, club)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', ''),
    -- teachers and admins are only ever promoted by an admin (set_user_role)
    case when new.raw_user_meta_data->>'role' = 'parent' then 'parent' else 'student' end,
    case when new.raw_user_meta_data->>'role' = 'parent' then null
         else nullif(new.raw_user_meta_data->>'club', '') end
  )
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

