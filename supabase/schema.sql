-- Exam questions for a student, options shuffled, correct answer hidden.
create or replace function public.get_exam(p_club text, p_level text)
returns table (id bigint, question text, options text[])
language sql volatile security definer set search_path = public as $$
  select q.id, q.question,
         (select array_agg(o order by random())
            from unnest(array[q.option_a, q.option_b, q.option_c, q.option_d]) as o)
    from public.exam_questions q
   where q.club = p_club and q.level = p_level
     and (public.is_teacher() or p_club = public.my_club())
   order by q.created_at;
$$;

-- Grades the exam on the server and records the attempt.
-- p_answers = {"<question id>": "<chosen option text>", ...}
create or replace function public.submit_exam(p_club text, p_level text, p_answers jsonb)
returns table (score int, passed boolean, correct int, total int)
language plpgsql security definer set search_path = public as $$
declare
  v_total int; v_correct int; v_score int; v_passed boolean;
begin
  if auth.uid() is null then raise exception 'Not signed in'; end if;
  if p_club is distinct from public.my_club() then raise exception 'This exam is not for your club'; end if;

  select count(*), count(*) filter (where p_answers->>(q.id::text) = q.option_a)
    into v_total, v_correct
    from public.exam_questions q
   where q.club = p_club and q.level = p_level;

  if v_total = 0 then raise exception 'No questions for this level yet'; end if;

  v_score  := round(v_correct * 100.0 / v_total);
  v_passed := v_score >= 70;

  insert into public.exam_attempts (student_id, club, level, score, passed)
  values (auth.uid(), p_club, p_level, v_score, v_passed);

  return query select v_score, v_passed, v_correct, v_total;
end $$;

-- Top readers of a club over the last N days (names only — no emails).
-- p_club = null → every club (teachers).
create or replace function public.club_leaderboard(p_club text default null, p_days int default 7)
returns table (student_id uuid, full_name text, club text, books bigint, days_active bigint)
language sql stable security definer set search_path = public as $$
  select r.student_id, p.full_name, p.club,
         count(distinct r.material_id) as books,
         count(distinct r.read_on)     as days_active
    from public.material_reads r
    join public.profiles p on p.id = r.student_id
   where r.read_on >= current_date - greatest(p_days, 1) + 1
     and (case when public.is_teacher() then (p_club is null or p.club = p_club)
               else p.club = public.my_club() end)
   group by r.student_id, p.full_name, p.club
   order by books desc, days_active desc, p.full_name
   limit 10;
$$;

-- Most opened books (teacher insight).
create or replace function public.popular_materials(p_days int default 30)
returns table (material_id bigint, title text, club text, level text, readers bigint)
language sql stable security definer set search_path = public as $$
  select m.id, m.title, m.club, m.level, count(distinct r.student_id)
    from public.material_reads r
    join public.materials m on m.id = r.material_id
   where public.is_teacher()
     and r.read_on >= current_date - greatest(p_days, 1) + 1
   group by m.id
   order by 5 desc, m.title
   limit 5;
$$;

grant execute on function public.get_exam(text, text)                to authenticated;
grant execute on function public.submit_exam(text, text, jsonb)      to authenticated;
grant execute on function public.club_leaderboard(text, int)          to authenticated;
grant execute on function public.popular_materials(int)               to authenticated;

