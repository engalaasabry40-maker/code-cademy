create or replace function public.set_user_role(p_user uuid, p_role text, p_club text default null)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Only an admin can change roles'; end if;
  if p_role not in ('student','parent','teacher','admin') then raise exception 'Unknown role %', p_role; end if;
  if p_user = auth.uid() and p_role <> 'admin' then raise exception 'You cannot remove your own admin access'; end if;
  update public.profiles
     set role = p_role,
         club = case when p_role = 'student' then coalesce(p_club, club) else club end
   where id = p_user;
end $$;

-- ----- parents -----
create or replace function public.link_child(p_code text)
returns table (student_id uuid, full_name text, club text)
language plpgsql security definer set search_path = public as $$
declare v_student public.profiles%rowtype;
begin
  if public.my_role() <> 'parent' then raise exception 'Only parent accounts can link a child'; end if;
  select * into v_student from public.profiles
   where link_code = upper(trim(p_code)) and role = 'student';
  if not found then raise exception 'No student found with this code'; end if;
  insert into public.parent_links (parent_id, student_id) values (auth.uid(), v_student.id)
  on conflict do nothing;
  return query select v_student.id, v_student.full_name, v_student.club;
end $$;

-- everything a parent (or teacher) needs to follow one student
create or replace function public.student_report(p_student uuid)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v jsonb;
begin
  if not (public.is_teacher() or public.is_parent_of(p_student) or p_student = auth.uid()) then
    raise exception 'Not allowed';
  end if;
  select jsonb_build_object(
    'student',   (select jsonb_build_object('id', id, 'full_name', full_name, 'club', club) from public.profiles where id = p_student),
    'books_week',(select count(distinct material_id) from public.material_reads where student_id = p_student and read_on > current_date - 7),
    'books_total',(select count(distinct material_id) from public.material_reads where student_id = p_student),
    'read_days', (select coalesce(jsonb_agg(d order by d desc), '[]') from (select distinct read_on d from public.material_reads
                    where student_id = p_student and read_on > current_date - 60) x),
    'exams',     (select coalesce(jsonb_agg(jsonb_build_object('level', level, 'score', score, 'passed', passed, 'at', created_at) order by created_at desc), '[]')
                    from (select * from public.exam_attempts where student_id = p_student order by created_at desc limit 10) e),
    'progress',  (select coalesce(jsonb_agg(jsonb_build_object('status', status, 'note', note, 'at', created_at) order by created_at desc), '[]')
                    from (select * from public.progress where student_id = p_student order by created_at desc limit 10) g)
  ) into v;
  return v;
end $$;

-- ----- chat -----
-- the conversations the signed-in person can see, newest first, with unread counts
create or replace function public.chat_inbox()
returns table (student_id uuid, student_name text, club text, last_body text, last_sender text,
               last_at timestamptz, unread bigint)
language sql stable security definer set search_path = public as $$
  with visible as (
    select p.id, p.full_name, p.club from public.profiles p
     where p.role = 'student' and (
           public.is_teacher() or p.id = auth.uid() or public.is_parent_of(p.id))
  )
  select v.id, v.full_name, v.club, last.body, last.sender_name, last.created_at,
         (select count(*) from public.messages m
           where m.student_id = v.id and m.sender_id <> auth.uid()
             and (public.is_teacher() or public.is_parent_of(v.id) or not m.private)
             and m.created_at > coalesce((select r.last_read_at from public.chat_reads r
                                           where r.user_id = auth.uid() and r.student_id = v.id), 'epoch'))
    from visible v
    left join lateral (
      select m.body, m.sender_name, m.created_at from public.messages m
       where m.student_id = v.id
         and (public.is_teacher() or public.is_parent_of(v.id) or not m.private)
       order by m.created_at desc limit 1) last on true
   order by last.created_at desc nulls last, v.full_name
   limit 300;
$$;

-- ----- certificates -----
create or replace function public.my_certificates(p_student uuid default null)
returns table (id text, full_name text, club text, level text, score int, issued_at timestamptz)
language sql stable security definer set search_path = public as $$
  select distinct on (a.level) a.id::text, p.full_name, a.club, a.level, a.score, a.created_at
    from public.exam_attempts a join public.profiles p on p.id = a.student_id
   where a.passed
     and a.student_id = coalesce(p_student, auth.uid())
     and (a.student_id = auth.uid() or public.is_teacher() or public.is_parent_of(a.student_id))
   order by a.level, a.score desc, a.created_at;
$$;

