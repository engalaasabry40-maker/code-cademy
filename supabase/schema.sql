create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  full_name   text not null default '',
  role        text not null default 'student' check (role in ('student','teacher','admin')),
  club        text,
  created_at  timestamptz not null default now()
);

create table if not exists public.materials (
  id           bigint generated by default as identity primary key,
  club         text not null,
  level        text not null,
  title        text not null,
  file_path    text not null,
  uploaded_by  uuid references public.profiles(id) on delete set null,
  created_at   timestamptz not null default now()
);
-- extra columns used by the upgraded library (added safely on old databases)
alter table public.materials add column if not exists file_name text;
alter table public.materials add column if not exists file_size bigint;
alter table public.materials add column if not exists mime_type text;

create table if not exists public.exam_questions (
  id          bigint generated by default as identity primary key,
  club        text not null,
  level       text not null,
  question    text not null,
  option_a    text not null,   -- always the correct answer
  option_b    text not null,
  option_c    text not null,
  option_d    text not null,
  created_by  uuid references public.profiles(id) on delete set null,
  created_at  timestamptz not null default now()
);

create table if not exists public.exam_attempts (
  id          bigint generated by default as identity primary key,
  student_id  uuid not null references public.profiles(id) on delete cascade,
  club        text not null,
  level       text not null,
  score       int  not null,
  passed      boolean not null,
  created_at  timestamptz not null default now()
);

create table if not exists public.progress (
  id          bigint generated by default as identity primary key,
  student_id  uuid not null references public.profiles(id) on delete cascade,
  status      text,
  note        text,
  created_at  timestamptz not null default now()
);

create table if not exists public.notifications (
  id          bigint generated by default as identity primary key,
  club        text,            -- null = every club
  title       text not null,
  body        text not null,
  created_by  uuid references public.profiles(id) on delete set null,
  created_at  timestamptz not null default now()
);

-- NEW: every time a student opens a book we log it → streaks + leaderboard
create table if not exists public.material_reads (
  id           bigint generated by default as identity primary key,
  student_id   uuid not null references public.profiles(id) on delete cascade,
  material_id  bigint not null references public.materials(id) on delete cascade,
  club         text,
  read_on      date not null default current_date,
  created_at   timestamptz not null default now(),
  unique (student_id, material_id, read_on)
);

create index if not exists materials_club_level_idx on public.materials (club, level, created_at desc);
create index if not exists exam_q_club_level_idx    on public.exam_questions (club, level);
create index if not exists reads_student_idx        on public.material_reads (student_id, read_on desc);
create index if not exists reads_club_idx           on public.material_reads (club, read_on desc);

